})
   .WithName("HealthCheck")
   .WithTags("Health")
   .AllowAnonymous();

// Detailed health check endpoint with DB and Docker verification
app.MapGet("/health/detailed", async (AppDbContext dbContext, DockerService dockerService) =>
{
    Dictionary<string, object> checks = new();
    DateTime startTime = DateTime.UtcNow;
    bool isHealthy = true;

    // Check Database
    try
    {
        await dbContext.Database.CanConnectAsync();
        int userCount = await dbContext.Users.CountAsync();
        checks["database"] = new
        {
            status = "Healthy",
            description = "SQLite database is accessible",
            userCount = userCount
        };
    }
    catch (Exception ex)
    {
        isHealthy = false;
        checks["database"] = new
        {
            status = "Unhealthy",
            description = "Cannot connect to database",
            error = ex.Message
        };
    }

    // Check Docker
    try
    {
        List<Lighthouse.DTOs.ContainerDto> containers = await dockerService.ListContainersAsync(true);
        checks["docker"] = new
        {
            status = "Healthy",
            description = "Docker daemon is reachable",
            containerCount = containers.Count
        };
    }
    catch (Exception ex)
    {
        isHealthy = false;
        checks["docker"] = new
        {
            status = "Unhealthy",
            description = "Cannot connect to Docker daemon",
            error = ex.Message
        };
    }

    TimeSpan totalDuration = DateTime.UtcNow - startTime;

    var response = new
    {
        status = isHealthy ? "Healthy" : "Unhealthy",
        checks = checks,
        totalDuration = totalDuration.ToString(@"hh\:mm\:ss\.fffffff"),
        timestamp = DateTime.UtcNow
    };

    return isHealthy ? Results.Ok(response) : Results.StatusCode(503);
})
   .WithName("HealthCheckDetailed")
   .WithTags("Health")
   // Detailed health exposes user/container counts and raw dependency error messages,
   // so it must not be anonymous. The simple /health endpoint stays public for the
   // Docker container healthcheck.
   .RequireAuthorization(new Microsoft.AspNetCore.Authorization.AuthorizeAttribute { Roles = "admin" });

app.MapControllers();

// Log when application is ready and mark instance as ready
IHostApplicationLifetime lifetime = app.Services.GetRequiredService<IHostApplicationLifetime>();
lifetime.ApplicationStarted.Register(async () =>
{
    IInstanceIdentifierService instanceService = app.Services.GetRequiredService<IInstanceIdentifierService>();

    string[] urls = app.Urls.ToArray();
    if (urls.Length > 0)
    {
        Log.Information("Lighthouse Backend is ready and listening on: {Urls}", string.Join(", ", urls));
    }
    else
    {
        Log.Information("Lighthouse Backend is ready and listening");
    }

    // Verify DB accessibility before marking as ready
    try
    {
        using IServiceScope scope = app.Services.CreateScope();
        AppDbContext dbContext = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        await dbContext.Database.CanConnectAsync();

        // Mark instance as ready
        instanceService.SetReady();
        double uptimeMs = (DateTime.UtcNow - instanceService.StartupTimestamp).TotalMilliseconds;
        Log.Information("Instance {InstanceId} ready after {UptimeMs:F0}ms",
            instanceService.InstanceId, uptimeMs);
    }
    catch (Exception ex)
    {
        Log.Error(ex, "Readiness checks failed - instance {InstanceId} NOT marked as ready",
            instanceService.InstanceId);
    }

    // Log self-filter detection result
    try
    {
        ISelfFilterService selfFilter = app.Services.GetRequiredService<ISelfFilterService>();
        string? selfProject = await selfFilter.GetSelfProjectNameAsync();
        string? selfContainerId = await selfFilter.GetSelfContainerIdAsync();

        if (selfProject != null)
        {
            Log.Information(
                "Self-filter active: project '{SelfProject}', container '{SelfContainerId}' will be hidden from all lists",
                selfProject, selfContainerId);
        }
        else if (selfContainerId != null)
        {
            Log.Information(
                "Self-filter active: standalone container '{SelfContainerId}' will be hidden from all lists",
                selfContainerId);
        }
        else
        {
            Log.Information("Self-filter inactive: not running in Docker");
        }
    }
    catch (Exception ex)
    {
        Log.Warning(ex, "Failed to log self-filter detection result");
    }
});

lifetime.ApplicationStopping.Register(() =>
{
    Log.Information("Lighthouse Backend is stopping...");
});

Log.Information("Lighthouse Backend starting...");
app.Run();
Log.Information("Lighthouse Backend stopped");
