// Configure JWT Authentication
string jwtSecret = builder.Configuration["Jwt:Secret"] ?? string.Empty;
if (string.IsNullOrWhiteSpace(jwtSecret))
{
    throw new InvalidOperationException(
        "JWT Secret is not configured. Please set the JWT_SECRET environment variable or Jwt:Secret in appsettings.json. " +
        "The secret must be at least 32 characters long for security.");
}
if (jwtSecret.Length < 32)
{
    throw new InvalidOperationException(
        $"JWT Secret must be at least 32 characters long. Current length: {jwtSecret.Length}. " +
        "Please set a secure JWT_SECRET environment variable.");
}
// Fail fast in production if the shipped placeholder secret was never replaced.
if (builder.Environment.IsProduction() &&
    jwtSecret == "CHANGE-THIS-SECRET-KEY-IN-PRODUCTION-MIN-32-CHARS")
{
    throw new InvalidOperationException(
        "JWT Secret is still the default placeholder. Set a unique JWT_SECRET before running in production.");
}
string jwtIssuer = builder.Configuration["Jwt:Issuer"] ?? "lighthouse";
string jwtAudience = builder.Configuration["Jwt:Audience"] ?? "lighthouse-client";

builder.Services.AddAuthentication(options =>
{
    options.DefaultAuthenticateScheme = JwtBearerDefaults.AuthenticationScheme;
    options.DefaultChallengeScheme = JwtBearerDefaults.AuthenticationScheme;
})
.AddJwtBearer(options =>
{
    options.TokenValidationParameters = new TokenValidationParameters
    {
        ValidateIssuer = true,
        ValidateAudience = true,
        ValidateLifetime = true,
        ValidateIssuerSigningKey = true,
        ValidIssuer = jwtIssuer,
        ValidAudience = jwtAudience,
        IssuerSigningKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(jwtSecret)),
        ClockSkew = TimeSpan.FromMinutes(5)
    };

    // Configure JWT authentication for SSE endpoints
    // SSE sends the token in the query string (access_token parameter)
    options.Events = new JwtBearerEvents
    {
        OnMessageReceived = context =>
        {
            Microsoft.Extensions.Primitives.StringValues accessToken = context.Request.Query["access_token"];

            // If the request is for our SSE endpoints
            PathString path = context.HttpContext.Request.Path;
            if (!string.IsNullOrEmpty(accessToken) &&
                (path.StartsWithSegments("/api/events") ||
                 (path.Value != null && path.Value.Contains("/logs/stream"))))
            {
                context.Token = accessToken;
            }

            return Task.CompletedTask;
        },

        // Enforce the per-user security stamp so access tokens can be revoked before
        // their natural expiry (password change, disable, role change). The current
        // stamp/enabled state is cached briefly to avoid a DB hit on every request.
        OnTokenValidated = async context =>
        {
            string? idClaim = context.Principal?.FindFirst(System.Security.Claims.ClaimTypes.NameIdentifier)?.Value;
            string? stampClaim = context.Principal?.FindFirst("sstamp")?.Value;

            if (!int.TryParse(idClaim, out int uid) || string.IsNullOrEmpty(stampClaim))
            {
                context.Fail("Invalid token subject");
                return;
            }

            Microsoft.Extensions.Caching.Memory.IMemoryCache cache =
                context.HttpContext.RequestServices.GetRequiredService<Microsoft.Extensions.Caching.Memory.IMemoryCache>();

            Lighthouse.Services.Security.UserSecurityInfo? info =
                await cache.GetOrCreateAsync(Lighthouse.Services.Security.SecurityStampCache.Key(uid), async entry =>
                {
                    entry.AbsoluteExpirationRelativeToNow = Lighthouse.Services.Security.SecurityStampCache.Ttl;
                    AppDbContext db = context.HttpContext.RequestServices.GetRequiredService<AppDbContext>();
                    return await db.Users
                        .Where(u => u.Id == uid)
                        .Select(u => new Lighthouse.Services.Security.UserSecurityInfo(u.SecurityStamp, u.IsEnabled))
                        .FirstOrDefaultAsync();
                });

            if (info is null || !info.IsEnabled || info.SecurityStamp != stampClaim)
            {
                context.Fail("Security stamp mismatch");
            }
        }
    };
});

